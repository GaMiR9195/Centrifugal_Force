package com.playsi.aero_cam_sync.client.aim;

/**
 * Окно, внутри которого воронка Sable обязана отдать НАСТОЯЩИЙ глаз, без наклонной поправки.
 *
 * <p>Инверсия прежней схемы. Раньше поправка применялась только внутри {@link PickScope}, и
 * из-за этого любой код вне пика получал гибрид: направление ({@code getViewVector}) мы тилтим
 * глобально, а начало — нет. Такой луч не совпадал ни с перекрестием, ни с ванилой (симптом
 * Dashpanels: модуль панели нажимается со сдвигом, см. {@code ACS-PITFALLS.md}).</p>
 *
 * <p>Теперь наоборот: поправка применяется везде, где спрашивают глаз локального игрока, а
 * исключения перечислены явно. Перепись потребителей воронки 2026-08-03 дала ровно два таких
 * места, оба — собственные рендерные пути Sable в {@code EntityRenderer}:</p>
 * <ul>
 *   <li>{@code getPackedLightCoords} — световой пробник (иначе поедет освещение);</li>
 *   <li>{@code shouldRender} — отбор сущностей по видимости (иначе поедут ники и отсечение).</li>
 * </ul>
 *
 * <p><b>Цена инверсии.</b> Ошибка в списке исключений теперь портит картинку, а не прицел —
 * раньше было наоборот. Не проверены частицы, звук и водная окклюзия: если они тоже
 * спрашивают воронку, добавятся сюда же.</p>
 *
 * <p>Счётчик, а не флаг: вызовы вложены друг в друга ({@code EntityRenderDispatcher} →
 * {@code EntityRenderer}). Сбрасывается в начале каждого пика, чтобы незакрытое окно
 * (исключение в чужом коде между HEAD и RETURN) не отключило наклон навсегда.</p>
 */
public final class RenderEyeScope {

    private RenderEyeScope() {}

    private static int depth = 0;

    public static void enter() {
        depth++;
    }

    public static void exit() {
        if (depth > 0) depth--;
    }

    public static boolean isActive() {
        return depth > 0;
    }

    /** Страховка от незакрытого окна: зовётся в начале пика. */
    public static void reset() {
        depth = 0;
    }
}
